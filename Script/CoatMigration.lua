-- Save-game migration for the coats.
--
-- RLRM saves no visual index per animal: the model is picked again from the subType and age on every load.
-- What it does save is `variation` - the animal's place in its breed's coat list for that age (the visual's
-- texture tiles, filtered by textureIndexes). Those lists are not the same under RLRM on its own, under
-- each released version of this pack and now (coats moved to other atlas tiles, breeds gained coats, a list
-- was reordered), so the same number can be another coat today: a Hereford or Highland changing colour
-- on loading an older save.
--
-- CoatMigrationData (generated by blender/make_coat_migration.py from every released version's files,
-- matching the coat images) maps, per old setup and saved subType and age band, each old place to the place
-- of the same coat now. The setup a save was last written with comes from its mod list
-- (missionInfo.mods): this pack's version there, or RLRM without this pack. A save written by this version
-- needs nothing, so every save is migrated once - on the next save its mod list holds this version.
--
-- The hook wraps RLRM's Animal.loadFromXMLFile (husbandries, dealers, trailers): it reads the subType name
-- as saved (before Migration.lua's renames, so a 1.0.x COW_HEREFORD_PACK animal uses that subType's list).

CoatMigration = {}

local TAG = "[CowBreedsRLRM/CoatMigration]"
local MOD_NAME = g_currentModName
local RLRM_NAME = "FS25_RealisticLivestockRM"

local function logf(fmt, ...) print(string.format(TAG .. " " .. fmt, ...)) end

--- "1.0.4.0" -> comparable number (four parts, missing ones 0)
local function versionNumber(v)
    local n, i = 0, 0
    for part in string.gmatch(tostring(v or ""), "%d+") do
        if i < 4 then
            n = n * 1000 + tonumber(part)
            i = i + 1
        end
    end
    for _ = i + 1, 4 do n = n * 1000 end
    return n
end

--- The data key for a save last written with this pack at version `saved`: the newest released setup not
--- newer than it (a hotfix keeps its release's lists), nil when it is this version or newer.
function CoatMigration.packSource(saved, current)
    local s = versionNumber(saved)
    if s >= versionNumber(current) then return nil end
    local best, bestN
    for key, _ in pairs(CoatMigrationData) do
        if key ~= "RLRM" then
            local n = versionNumber(key)
            if n <= s and (bestN == nil or n > bestN) then best, bestN = key, n end
        end
    end
    if best == nil then          -- older than the first release in the table: its lists are the closest
        for key, _ in pairs(CoatMigrationData) do
            if key ~= "RLRM" and (bestN == nil or versionNumber(key) < bestN) then best, bestN = key, versionNumber(key) end
        end
    end
    return best
end

--- Which setup the save being loaded was written with (a CoatMigrationData key), or nil: a new game, a save
--- of this version, or one without RLRM.
function CoatMigration.detectSource(mods, current)
    if mods == nil then return nil end
    local ours, rlrm
    for _, mod in ipairs(mods) do
        local name = tostring(mod.modName)
        if name == MOD_NAME or string.find(name, "^FS25_CowBreedsRLRM") ~= nil then ours = mod end
        if name == RLRM_NAME then rlrm = true end
    end
    if ours ~= nil then
        return CoatMigration.packSource(ours.version, current), ours.version
    end
    if rlrm then return "RLRM", nil end
    return nil
end

--- The current place of the coat a loaded animal had (nil: unchanged).
function CoatMigration.remap(source, savedSubType, age, variation)
    local data = source ~= nil and CoatMigrationData[source] or nil
    local rows = data ~= nil and savedSubType ~= nil and data[savedSubType] or nil
    if rows == nil or variation == nil then return nil end
    for _, row in ipairs(rows) do
        if age >= row[1] and age <= row[2] then
            local new = row[3][variation]
            if new ~= nil and new ~= variation then return new end
            return nil
        end
    end
    return nil
end

local state = { source = false, counts = {}, total = 0 }       -- source false: not looked up yet

local function currentSource()
    if state.source == false then
        local mission = g_currentMission
        local info = mission ~= nil and mission.missionInfo or nil
        local mod = g_modManager ~= nil and g_modManager:getModByName(MOD_NAME) or nil
        local source, savedVersion = CoatMigration.detectSource(info ~= nil and info.mods or nil, mod ~= nil and mod.version or "0")
        if source ~= nil and next(CoatMigrationData[source] or {}) == nil then
            source = nil                                       -- that setup's lists are all still the same
        end
        state.source = source
        if source ~= nil then
            logf("save last written with %s - coats of older lists are moved to the same coat now",
                 savedVersion ~= nil and ("this pack " .. tostring(savedVersion)) or "RLRM without this pack")
        end
    end
    return state.source
end

local function migrated(animal, xmlFile, key)
    if animal == nil or xmlFile == nil or key == nil then return end
    local source = currentSource()
    if source == nil then return end
    local saved = xmlFile:getString(key .. "#subType")
    local new = CoatMigration.remap(source, saved, animal.age or 0, animal.variation)
    if new ~= nil then
        animal.variation = new
        state.counts[saved] = (state.counts[saved] or 0) + 1
        state.total = state.total + 1
    end
end

local hooked = false

function CoatMigration.install()
    if hooked then return true end
    local rlrm = FS25_RealisticLivestockRM                   -- RLRM's mod environment (its globals live there)
    local Animal = rlrm ~= nil and rlrm.Animal or nil
    if Animal == nil or Animal.loadFromXMLFile == nil then return false end
    local load = Animal.loadFromXMLFile
    Animal.loadFromXMLFile = function(xmlFile, key, ...)
        local results = { load(xmlFile, key, ...) }
        migrated(results[1], xmlFile, key)
        return unpack(results, 1, table.maxn(results))
    end
    hooked = true
    return true
end

function CoatMigration:loadMap(_)
    if not CoatMigration.install() then
        logf("%s not found - coat migration inactive", RLRM_NAME)
    end
end

--- The tally, once the save's animals are in (FSBaseMission.onStartMission: listeners don't get it)
function CoatMigration.report()
    if state.total > 0 then
        local parts = {}
        for name, n in pairs(state.counts) do table.insert(parts, string.format("%s %d", name, n)) end
        table.sort(parts)
        logf("%d animals' coats moved to their place in the current lists (%s)", state.total, table.concat(parts, ", "))
    end
end

function CoatMigration:deleteMap()
    state.source, state.counts, state.total = false, {}, 0
end

CoatMigration.install()
addModEventListener(CoatMigration)
if FSBaseMission ~= nil and FSBaseMission.onStartMission ~= nil then
    FSBaseMission.onStartMission = Utils.appendedFunction(FSBaseMission.onStartMission, CoatMigration.report)
end
